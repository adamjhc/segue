let failures = 0;
for (const [task, want] of TASKS) {
  const got = stepCategory(task).id;
  if (got !== want) {
    failures++;
    console.log(`${task.padEnd(40)} got ${got.padEnd(9)} want ${want}`);
  }
}
console.log(`${TASKS.length - failures}/${TASKS.length} tasks matched`);

for (const category of STEP_CATEGORIES) {
  const shown = new Set();
  let last;
  for (let i = 0; i < category.steps.length * 2; i++) {
    const step = suggestStep(category.id === "general" ? "" : TASKS.find(([, c]) => c === category.id)[0], last);
    if (i < category.steps.length && shown.has(step)) { failures++; console.log(`${category.id}: repeated before the pool ran out`); break; }
    if (step === last) { failures++; console.log(`${category.id}: same step twice in a row`); break; }
    shown.add(step);
    last = step;
  }
  if (new Set(category.steps).size !== category.steps.length) { failures++; console.log(`${category.id}: duplicate steps`); }
}

process.exit(failures ? 1 : 0);
